#!/bin/bash

# -----------------------------------------
# VPS 回程路由检测脚本（NextTrace 版本）
# 作者：FrankLiangCN（适配 BusyBox / Alpine / Debian）
# -----------------------------------------

set -e

# 探测目标（可自行扩展）
declare -A TARGETS=(
  ["北京电信"]="219.141.136.10"
  ["北京联通"]="202.106.195.68"
  ["北京移动"]="221.179.155.161"
  ["上海电信"]="202.96.209.133"
  ["上海联通"]="210.22.97.1"
  ["上海移动"]="211.136.112.200"
  ["广州电信"]="58.60.188.222"
  ["广州联通"]="210.21.196.6"
  ["广州移动"]="120.196.165.24"
  ["深圳电信"]="58.60.188.222"
  ["深圳联通"]="120.80.157.101"
  ["深圳移动"]="120.196.165.24"
  ["深圳电信163"]="113.96.0.0"
  ["深圳电信CN2"]="59.43.0.1"
  ["深圳联通169"]="210.21.0.1"
  ["深圳联通9929"]="218.104.0.1"
  ["深圳移动CMNET"]="221.179.155.161"
  ["深圳移动CMI"]="223.120.128.1"
)

# 检查依赖
check_dep() {
  if ! command -v nexttrace >/dev/null 2>&1; then
    echo "未检测到 nexttrace，正在安装..."
    curl -sN https://nxtrace.org/nt | bash
    echo "nexttrace 安装完成"
  fi
}

# 执行 nexttrace
run_trace() {
  name="$1"
  ip="$2"

  echo ""
  echo "============================================"
  echo " 回程检测：$name ($ip)"
  echo "============================================"

  nexttrace -q 1 -g cn "$ip"
}

# 主程序
main() {
  check_dep

  echo "============================================"
  echo " VPS 回程路由检测（NextTrace）"
  echo "============================================"
  echo "开始检测..."

  for name in "${!TARGETS[@]}"; do
    run_trace "$name" "${TARGETS[$name]}"
  done

  echo "============================================"
  echo "检测完成"
  echo "============================================"
}

main
